import type { Metadata } from "next";

import { LEGAL } from "@/lib/legal";

/**
 * The one host search engines should know about.
 *
 * A constant rather than an environment variable on purpose: a canonical tag that follows a
 * misconfigured deployment tells Google the real site is a duplicate of a preview. Deploy
 * previews and the platform's own hostname keep pointing here, which is what they should do.
 */
export const SITE_URL = "https://untiered.tech";

/**
 * Every page that should appear in search results, and so everything in the sitemap.
 *
 * Courses and the Arena are not here because they redirect signed-out visitors to /login
 * (owner, 21 September 2026): a crawler has no session, so listing them would submit
 * redirects. `seo.test.ts` fails when a page is added without being classified.
 */
export const INDEXABLE_ROUTES = ["/", "/pricing", "/about", "/contact", "/privacy", "/terms", "/refund-policy"] as const;

/** Reachable without signing in, but nothing a searcher should land on. */
export const NOINDEX_PUBLIC_ROUTES = ["/login", "/upgrade", "/daily-challenge", "/auth/update-password", "/unsubscribe"] as const;

/** Keeps a page out of the index while still letting crawlers follow its links. */
export const NOINDEX_FOLLOW: NonNullable<Metadata["robots"]> = { index: false, follow: true };

export const rootMetadata: Metadata = {
  metadataBase: new URL(SITE_URL),
  title: {
    default: LEGAL.productName,
    template: `%s · ${LEGAL.productName}`,
  },
  description:
    "Voice-first AI mock interviews grounded in how interviews at real employers actually run — " +
    "product companies, service-based IT, consulting, European employers and beyond.",
  // No canonical here: children inherit it, and every page would claim to be the homepage.
  openGraph: { type: "website", siteName: LEGAL.productName },
  twitter: { card: "summary_large_image" },
};

/** Generated by app/opengraph-image.tsx. Stated explicitly because a page that sets its own
 * `openGraph` replaces the layout's, and the file-based image goes with it. */
const SHARE_IMAGE = { url: "/opengraph-image", width: 1200, height: 630, alt: "Untiered: spoken AI mock interviews" };

/** Metadata for a page in `INDEXABLE_ROUTES`: its canonical URL and matching social tags. */
export function publicPageMetadata({
  title,
  description,
  path,
}: {
  title: string;
  description: string;
  path: (typeof INDEXABLE_ROUTES)[number];
}): Metadata {
  // Nested fields replace the layout's rather than merge, so these are restated in full. The
  // title template only reaches <title>, and the homepage's title has no template applied.
  const socialTitle = path === "/" ? title : `${title} · ${LEGAL.productName}`;
  return {
    title,
    description,
    alternates: { canonical: path },
    openGraph: { type: "website", siteName: LEGAL.productName, title: socialTitle, description, url: path, images: [SHARE_IMAGE] },
    twitter: { card: "summary_large_image", title: socialTitle, description, images: [SHARE_IMAGE] },
  };
}

/**
 * Who runs the site and what it is called, for the homepage.
 *
 * Only facts the site states elsewhere. There is deliberately no SoftwareApplication or
 * Product here: Google's rich result for those needs ratings or reviews, and there are none
 * to give. No `sameAs` until there are social profiles to name.
 */
export function homepageJsonLd() {
  const organizationId = `${SITE_URL}/#organization`;
  return {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "Organization",
        "@id": organizationId,
        name: LEGAL.productName,
        legalName: LEGAL.operatorName,
        url: `${SITE_URL}/`,
        // The square app icon: Google wants a logo of at least 112px, and the brand mark is smaller.
        logo: `${SITE_URL}/apple-icon.png`,
        email: LEGAL.contactEmail,
      },
      {
        "@type": "WebSite",
        "@id": `${SITE_URL}/#website`,
        name: LEGAL.productName,
        url: `${SITE_URL}/`,
        publisher: { "@id": organizationId },
      },
    ],
  };
}

/** JSON-LD for a `<script>` body. `<` is escaped so a value can never close the tag. */
export function serializeJsonLd(value: unknown): string {
  return JSON.stringify(value).replace(/</g, "\\u003c");
}

/**
 * False on Netlify deploy previews and branch deploys, and on Vercel previews. Both platforms
 * set these during the build, which is when robots.txt is generated.
 */
export function isProductionDeployment(env: NodeJS.ProcessEnv = process.env): boolean {
  if (env.CONTEXT && env.CONTEXT !== "production") return false;
  if (env.VERCEL_ENV && env.VERCEL_ENV !== "production") return false;
  return true;
}
